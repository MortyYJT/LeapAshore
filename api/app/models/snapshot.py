"""Official page text the advisor can quote (openspec snapshot-rag D4).

A page is one official URL at one snapshot; its chunks are that snapshot's visible text, boilerplate head
and tail removed, cut into pieces small enough to hand the model a few at a time. A page names its
school and, when it is a program's own page, the program. Nothing here stores where a snapshot lies on
disk: the sha256 and the URL name it (as `collect_pages` does, collect-queue D9).

Nothing here is a verification: a chunk is what the page said when it was fetched, shown as 待核验 with
its link and date. `verified_at` lives on `sources` and is written by a person only.
"""

from datetime import datetime

from pgvector.sqlalchemy import Vector
from sqlalchemy import Computed, DateTime, ForeignKey, Index, Integer, String, Text, func
from sqlalchemy.dialects.postgresql import TSVECTOR
from sqlalchemy.orm import Mapped, deferred, mapped_column

from app.db import Base
from app.models.program import EMBEDDING_DIM

# A chunk's text as an English full-text vector, generated by PostgreSQL (alembic f7c2d9a4e816).
CHUNK_TSV_SQL = "to_tsvector('english'::regconfig, text)"


class SnapshotPage(Base):
    """One official page and the snapshot its chunks were cut from."""

    __tablename__ = "snapshot_pages"

    id: Mapped[str] = mapped_column(String(36), primary_key=True)  # uuid5 of the URL
    url: Mapped[str] = mapped_column(Text, unique=True)
    # The requirement file's school key: the snapshot store's folder name, never a path.
    school_key: Mapped[str] = mapped_column(String(96), index=True)
    university_id: Mapped[str] = mapped_column(
        String(64), ForeignKey("universities.id", ondelete="CASCADE"), index=True
    )
    # The program whose own page this is; NULL for a page shared by many (an admissions or fees page).
    program_id: Mapped[str | None] = mapped_column(
        String(64), ForeignKey("programs.id", ondelete="SET NULL"), index=True
    )
    title: Mapped[str | None] = mapped_column(Text)
    snapshot_sha256: Mapped[str] = mapped_column(String(64))
    fetched_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    # The sha256 of the text that was chunked (after the boilerplate trim) and the chunker that cut it:
    # when both are the same, a re-ingest writes nothing.
    content_sha256: Mapped[str] = mapped_column(String(64))
    chunker: Mapped[str] = mapped_column(String(32))
    chunk_count: Mapped[int] = mapped_column(Integer)
    ingested_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())


class SnapshotChunk(Base):
    """A piece of a page's visible text, verbatim: a quote is checked against exactly this."""

    __tablename__ = "snapshot_chunks"
    __table_args__ = (Index("ix_snapshot_chunks_search_tsv", "search_tsv", postgresql_using="gin"),)

    id: Mapped[str] = mapped_column(String(36), primary_key=True)  # uuid5 of page id, sha and ordinal
    page_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("snapshot_pages.id", ondelete="CASCADE"), index=True
    )
    ordinal: Mapped[int] = mapped_column(Integer)
    text: Mapped[str] = mapped_column(Text)
    content_sha256: Mapped[str] = mapped_column(String(64))
    search_tsv = deferred(mapped_column(TSVECTOR, Computed(CHUNK_TSV_SQL, persisted=True)))


class SnapshotChunkEmbedding(Base):
    """A chunk's bge-m3 vector, with the model and the hash of the text it was made from (as
    `program_embeddings`, openspec hybrid-retrieval D5). Empty until an embedding key exists."""

    __tablename__ = "snapshot_chunk_embeddings"

    chunk_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("snapshot_chunks.id", ondelete="CASCADE"), primary_key=True
    )
    model: Mapped[str] = mapped_column(Text)
    content_sha256: Mapped[str] = mapped_column(String(64))
    embedding = mapped_column(Vector(EMBEDDING_DIM), nullable=False)
    embedded_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
